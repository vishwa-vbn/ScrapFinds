import type { VercelRequest, VercelResponse } from '@vercel/node';
import { verifyAdmin } from './_lib/verifyAdmin';

export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader('Cache-Control', 'no-store');

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  // Require admin authorization
  const auth = await verifyAdmin(req);
  if (!auth.ok) {
    return res.status(auth.status).json({ error: auth.msg });
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: 'GEMINI_API_KEY is not configured on server' });
  }

  const { title, description, category, condition } = req.body || {};
  if (!title && !description) {
    return res.status(400).json({ error: 'Title or description is required for translation' });
  }

  const prompt = `You are a professional local second-hand and scrap item catalog copywriter in India.
Translate and adapt the following item listing into natural, clear Kannada (kn) and Hindi (hi) suitable for local second-hand buyers.

Item details:
- Category: ${category || 'general'}
- Condition: ${condition || 'good'}
- Title: ${title || ''}
- Description: ${description || ''}

Requirements:
1. Translate the title concisely into natural Kannada and Hindi (keep brand/model names in easily recognizable script or standard brand transliteration, e.g. "Sony", "Samsung", "ಹೀರೋ").
2. Translate the description into clear, conversational, buyer-friendly language highlighting the working condition.
3. Return ONLY a single raw valid JSON object with exact structure:
{
  "kn": {
    "title": "ಕನ್ನಡ ಶೀರ್ಷಿಕೆ",
    "description": "ಕನ್ನಡ ವಿವರಣೆ"
  },
  "hi": {
    "title": "हिंदी शीर्षक",
    "description": "हिंदी विवरण"
  }
}
Do not wrap in markdown or backticks. Return valid JSON only.`;

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.2,
            responseMimeType: 'application/json',
          },
        }),
      }
    );

    if (!response.ok) {
      const errText = await response.text();
      console.error('Gemini API error:', response.status, errText);
      return res.status(502).json({ error: `Gemini API returned ${response.status}: ${errText}` });
    }

    const data: any = await response.json();
    const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) {
      return res.status(502).json({ error: 'No translation generated by Gemini' });
    }

    const cleanJson = candidateText.replace(/^```json/i, '').replace(/```$/i, '').trim();
    const parsed = JSON.parse(cleanJson);

    return res.status(200).json(parsed);
  } catch (err) {
    console.error('Translation error:', err);
    return res.status(500).json({ error: (err as Error).message || 'Failed to generate translations' });
  }
}
